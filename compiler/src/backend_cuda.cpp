#include "sigflow/backend_cuda.hpp"

#include <set>
#include <vector>

namespace sigflow {

namespace {

// A C++ string literal: "fixtures/it's.cf32" stays as is, quotes and backslashes are escaped.
std::string literal(const std::string& text)
{
    std::string out = "\"";
    for (char c : text) {
        if (c == '"' || c == '\\') {
            out += '\\';
        }
        out += c;
    }
    return out + "\"";
}

const char* element(const Node& node)
{
    return node.type.element == ElementType::Cf32 ? "cf32" : "float";
}

class CudaEmitter {
public:
    CudaEmitter(const Graph& graph, const Schedule& schedule, const Liveness& liveness,
                std::ostream& out)
        : graph_(graph), schedule_(schedule), liveness_(liveness), out_(out)
    {
    }

    void run(const std::string& program_name, bool reuse)
    {
        collect();
        out_ << "// Generated by sigflowc from " << program_name << ". Do not edit.\n"
             << "// Build: compiler/tools/build_cuda.sh THIS.cu PROGRAM; run it from the "
                "directory its\n"
             << "// paths are relative to: PROGRAM [--bench N] [--warmup W]. Prints a JSON "
                "report on stdout.\n"
             << "#include \"device_ops.hpp\"\n"
             << "#include \"pipeline_runtime.hpp\"\n\n"
             << "#include <cstdio>\n#include <exception>\n#include <vector>\n\n"
             << "int main(int argc, char** argv)\n"
             << "try {\n"
             << "    sigflow::Runtime rt(" << literal(program_name) << ", "
             << (fused() ? "true" : "false") << ", "
             << (reuse ? "true" : "false") << ", argc, argv);\n";
        setup();
        compute();
        finish();
        out_ << "} catch (const std::exception& e) {\n"
             << "    std::fprintf(stderr, \"error: %s\\n\", e.what());\n"
             << "    return 1;\n"
             << "}\n";
    }

private:
    bool fused() const
    {
        for (NodeId id : schedule_.order) {
            if (node(id).group >= 0) {
                return true;
            }
        }
        return false;
    }

    const Node& node(NodeId id) const { return graph_.nodes[static_cast<std::size_t>(id)]; }
    static std::string n(NodeId id) { return "n" + std::to_string(id); }
    std::string slot(NodeId id) const
    {
        const Node& v = node(id);
        return "rt.slot<" + std::string(element(v)) + ">("
               + std::to_string(liveness_.slot_of[static_cast<std::size_t>(id)]) + ")";
    }
    static std::string as_int(NodeId id) { return "static_cast<int>(" + n(id) + ")"; }

    // Live nodes in schedule order, split by what the program does with them.
    void collect()
    {
        for (NodeId id : schedule_.order) {
            const Node& v = node(id);
            if (v.op == Op::Capture) {
                captures_.push_back(id);
            } else if (v.op == Op::Emit) {
                emits_.push_back(id);
            }
        }
    }

    void setup()
    {
        out_ << "\n    // Captures, read once.\n";
        for (NodeId id : captures_) {
            out_ << "    const std::vector<cf32> h" << id << " = rt.read_capture("
                 << literal(node(id).path) << ");  // " << format_node(node(id)) << "\n";
        }

        out_ << "\n    // Samples in every value.\n";
        for (NodeId id : schedule_.order) {
            const Node& v = node(id);
            switch (v.op) {
            case Op::Capture:
                out_ << "    const std::size_t " << n(id) << " = h" << id << ".size();\n";
                break;
            case Op::Fir:
            case Op::Magnitude:
                out_ << "    const std::size_t " << n(id) << " = " << n(v.inputs[0]) << ";\n";
                break;
            case Op::Fft:
                out_ << "    const std::size_t " << n(id) << " = sigflow::padded_to_frames("
                     << n(v.inputs[0]) << ", " << v.n << ");\n";
                break;
            case Op::Xcorr:
                out_ << "    const std::size_t " << n(id) << " = " << n(v.inputs[0]) << " + "
                     << n(v.inputs[1]) << " - 1;\n";
                break;
            case Op::Emit:
                break;
            }
        }

        out_ << "\n    // Buffer slots from liveness analysis, each as large as the largest value "
                "it holds.\n";
        for (const LiveRange& range : liveness_.ranges) {
            const Node& v = node(range.node);
            out_ << "    rt.need(" << range.slot << ", " << n(range.node) << " * sizeof("
                 << element(v) << "));  // %" << range.node << "\n";
            // An FFT reads whole frames, so its input's slot also holds the zero padding.
            for (const Node& user : graph_.nodes) {
                if (graph_.live[static_cast<std::size_t>(user.id)] && user.op == Op::Fft
                    && user.inputs[0] == range.node) {
                    out_ << "    rt.need(" << range.slot << ", " << n(user.id)
                         << " * sizeof(cf32));  // %" << range.node << " padded for %" << user.id
                         << "\n";
                }
            }
        }
        out_ << "    rt.allocate_slots();\n";

        bool first = true;
        for (NodeId id : schedule_.order) {
            const Node& v = node(id);
            if (v.op == Op::Fir) {
                if (first) {
                    out_ << "\n    // Taps and FFT plans.\n";
                    first = false;
                }
                out_ << "    int taps" << id << " = 0;\n"
                     << "    const float* t" << id << " = rt.taps(" << literal(v.taps)
                     << ", taps" << id << ");\n";
            } else if (v.op == Op::Fft) {
                if (first) {
                    out_ << "\n    // Taps and FFT plans.\n";
                    first = false;
                }
                out_ << "    const cufftHandle plan" << id << " = rt.fft_plan(" << v.n << ", "
                     << n(id) << " / " << v.n << ");\n";
            }
        }

        out_ << "\n    // Host copies of the emitted values.\n";
        for (NodeId id : emits_) {
            const Node& value = node(node(id).inputs[0]);
            if (value.op != Op::Capture) {
                out_ << "    std::vector<" << element(value) << "> out" << id << "("
                     << n(value.id) << ");  // " << format_node(node(id)) << "\n";
            }
        }
    }

    void compute()
    {
        out_ << "\n    rt.run(\n        [&] {\n";
        for (NodeId id : captures_) {
            out_ << "            CUDA_CHECK(cudaMemcpy(" << slot(id) << ", h" << id << ".data(), "
                 << n(id) << " * sizeof(cf32), cudaMemcpyHostToDevice));\n";
        }
        out_ << "        },\n        [&] {\n";
        for (NodeId id : schedule_.order) {
            const Node& v = node(id);
            if (v.op == Op::Capture || v.op == Op::Emit) {
                continue;
            }
            out_ << "            // " << format_node(v) << "\n";
            switch (v.op) {
            case Op::Fir:
                if (v.group >= 0) {
                    fused_fir(v);
                    break;
                }
                out_ << "            fir_naive_device(" << slot(v.inputs[0]) << ", t" << id << ", "
                     << slot(id) << ", " << as_int(id) << ", taps" << id << ");\n"
                     << "            rt.count(\"fir\");\n";
                break;
            case Op::Fft: {
                const NodeId in = v.inputs[0];
                out_ << "            if (" << n(id) << " > " << n(in) << ") {  // zero the last "
                        "frame's padding\n"
                     << "                CUDA_CHECK(cudaMemsetAsync(" << slot(in) << " + " << n(in)
                     << ", 0, (" << n(id) << " - " << n(in) << ") * sizeof(cf32)));\n"
                     << "                rt.count(\"memset\");\n"
                     << "            }\n"
                     << "            spectrum_device(plan" << id << ", " << slot(in) << ", "
                     << slot(id) << ");\n"
                     << "            rt.count(\"cufft\");\n";
                break;
            }
            case Op::Magnitude:
                out_ << "            magnitude_device(" << slot(v.inputs[0]) << ", " << slot(id)
                     << ", " << as_int(id) << ");\n"
                     << "            rt.count(\"magnitude\");\n";
                break;
            case Op::Xcorr:
                out_ << "            xcorr_naive_device(" << slot(v.inputs[0]) << ", "
                     << slot(v.inputs[1]) << ", " << slot(id) << ", " << as_int(v.inputs[0])
                     << ", " << as_int(v.inputs[1]) << ");\n"
                     << "            rt.count(\"xcorr\");\n";
                break;
            case Op::Capture:
            case Op::Emit:
                break;
            }
        }
        out_ << "        },\n        [&] {\n";
        for (NodeId id : emits_) {
            const Node& value = node(node(id).inputs[0]);
            if (value.op != Op::Capture) {
                out_ << "            CUDA_CHECK(cudaMemcpy(out" << id << ".data(), "
                     << slot(value.id) << ", " << n(value.id) << " * sizeof(" << element(value)
                     << "), cudaMemcpyDeviceToHost));\n";
            }
        }
        out_ << "        });\n";
    }

    // A fusion group's FIRs are consecutive in the schedule (see schedule()): the first one emits
    // the batched launch for all of them, the rest only note where they went.
    void fused_fir(const Node& v)
    {
        if (!launched_groups_.insert(v.group).second) {
            out_ << "            // (in the fused launch above)\n";
            return;
        }
        std::vector<NodeId> members;
        for (NodeId id : schedule_.order) {
            if (node(id).group == v.group) {
                members.push_back(id);
            }
        }
        std::string x;
        std::string y;
        std::string counts;
        for (NodeId id : members) {
            const std::string sep = x.empty() ? "" : ", ";
            x += sep + slot(node(id).inputs[0]);
            y += sep + slot(id);
            counts += sep + as_int(id);
        }
        out_ << "            {  // fusion group " << v.group << ": " << members.size()
             << " FIRs, one launch\n"
             << "                const cf32* x[] = {" << x << "};\n"
             << "                cf32* y[] = {" << y << "};\n"
             << "                const int n[] = {" << counts << "};\n"
             << "                fir_naive_batched_device(x, y, n, " << members.size() << ", t"
             << v.id << ", taps" << v.id << ");\n"
             << "                rt.count(\"fir_batched\");\n"
             << "            }\n";
    }

    void finish()
    {
        out_ << "\n";
        for (NodeId id : emits_) {
            const Node& emit = node(id);
            const Node& value = node(emit.inputs[0]);
            const std::string data = value.op == Op::Capture ? "h" + std::to_string(value.id)
                                                             : "out" + std::to_string(id);
            const bool complex = value.type.element == ElementType::Cf32;
            out_ << "    rt." << (complex ? "write_cf32" : "write_f32") << "("
                 << literal(emit.path) << ", " << data << ");\n";
        }
        out_ << "    rt.report();\n    return 0;\n";
    }

    const Graph& graph_;
    const Schedule& schedule_;
    const Liveness& liveness_;
    std::ostream& out_;
    std::vector<NodeId> captures_;
    std::vector<NodeId> emits_;
    std::set<int> launched_groups_;
};

}  // namespace

void emit_cuda(const Graph& graph, const Schedule& schedule, const Liveness& liveness,
               const std::string& program_name, bool reuse, std::ostream& out)
{
    CudaEmitter(graph, schedule, liveness, out).run(program_name, reuse);
}

}  // namespace sigflow
